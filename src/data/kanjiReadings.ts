const HIRA_TO_KATA_OFFSET = 0x60;

function hiraganaToKatakana(text: string): string {
  let out = '';
  for (let i = 0; i < text.length; i += 1) {
    const code = text.charCodeAt(i);
    if (code >= 0x3041 && code <= 0x3096) {
      out += String.fromCharCode(code + HIRA_TO_KATA_OFFSET);
    } else {
      out += text[i];
    }
  }
  return out;
}

const KANJI_CHAR_RE = /[\u4e00-\u9faf]/;
const HIRAGANA_ONLY_RE = /^[\u3041-\u3096ー]+$/;

/**
 * Look up On'yomi (Katakana) and Kun'yomi (Hiragana) for a single Kanji character.
 * Uses the built-in JLPT N5–N1 dictionary first, and falls back to deriving readings
 * from the active Anki vocabulary cards when a rare kanji isn't listed statically.
 */
export function lookupKanjiReadings(
  kanji: string,
  fallbackCards?: readonly AnkiCard[],
): KanjiReadingEntry {
  const staticHit = KANJI_READINGS_MAP.get(kanji);
  if (staticHit) {
    return {
      onyomi: [...staticHit.onyomi],
      kunyomi: [...staticHit.kunyomi],
    };
  }

  if (!fallbackCards || fallbackCards.length === 0) {
    return { onyomi: [], kunyomi: [] };
  }

  const kunSet = new Set<string>();
  const onSet = new Set<string>();

  for (const card of fallbackCards) {
    if (card.cardKind === 'bunpou') continue;
    if (!card.word.includes(kanji)) continue;
    const furi = (card.furigana || '').trim();
    if (!furi || !HIRAGANA_ONLY_RE.test(furi)) continue;

    // Exact single-kanji word (e.g. 猫 -> ねこ) or kanji + okurigana (e.g. 食べる -> たべる)
    const kanjiCount = Array.from(card.word).filter((c) =>
      KANJI_CHAR_RE.test(c),
    ).length;

    if (kanjiCount === 1) {
      if (card.word === kanji) {
        kunSet.add(furi);
      } else if (card.word.startsWith(kanji)) {
        const suffix = card.word.slice(1);
        if (HIRAGANA_ONLY_RE.test(suffix) && furi.endsWith(suffix)) {
          const stem = furi.slice(0, furi.length - suffix.length);
          if (stem.length > 0) {
            kunSet.add(`${stem}.${suffix}`);
          }
        }
      }
    } else if (kanjiCount === 2 && card.word.length === 2 && furi.length >= 2) {
      // Heuristic compound hint for rare kanji not in static dictionary
      const pos = card.word.indexOf(kanji);
      const mid = Math.floor(furi.length / 2);
      const slice = pos === 0 ? furi.slice(0, mid) : furi.slice(mid);
      if (slice.length >= 1 && slice.length <= 3) {
        onSet.add(hiraganaToKatakana(slice));
      }
    }

    if (kunSet.size >= 2 && onSet.size >= 2) break;
  }

  return {
    onyomi: Array.from(onSet).slice(0, 3),
    kunyomi: Array.from(kunSet).slice(0, 3),
  };
}
